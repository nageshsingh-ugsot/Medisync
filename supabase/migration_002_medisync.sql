create table if not exists public.medicines (
  id uuid primary key default gen_random_uuid(),
  pharmacy_id uuid not null references public.pharmacies(id) on delete cascade,
  brand_name text not null check (char_length(brand_name) between 1 and 160),
  generic_name text not null check (char_length(generic_name) between 1 and 160),
  strength text not null default '',
  dosage_form text not null check (dosage_form in ('tablet','capsule','syrup','powder','injection','cream','drops','inhaler','strip','bottle','box','other')),
  pack_size text not null default '',
  manufacturer text,
  image_url text,
  unit text not null default 'tablets' check (unit in ('tablets','strips','bottles','boxes')),
  reorder_level integer not null default 10 check (reorder_level >= 0),
  selling_price numeric(12,2) not null default 0 check (selling_price >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.batches (
  id uuid primary key default gen_random_uuid(),
  medicine_id uuid not null references public.medicines(id) on delete cascade,
  pharmacy_id uuid not null references public.pharmacies(id) on delete cascade,
  batch_number text not null check (char_length(batch_number) between 1 and 100),
  mfg_date date,
  expiry_date date not null,
  quantity integer not null default 0 check (quantity >= 0),
  purchase_price numeric(12,2) not null default 0 check (purchase_price >= 0),
  selling_price numeric(12,2) not null default 0 check (selling_price >= 0),
  created_at timestamptz not null default now(),
  constraint batches_medicine_batch_unique unique (medicine_id, batch_number)
);

create table if not exists public.catalogue_seed (
  id bigint generated by default as identity primary key,
  brand_name text not null,
  generic_name text not null,
  strength text not null default '',
  dosage_form text not null,
  pack_size text not null default '',
  manufacturer text
);

create unique index if not exists catalogue_seed_variant_unique
  on public.catalogue_seed (brand_name, generic_name, strength, dosage_form, pack_size);
create index if not exists medicines_pharmacy_name_idx
  on public.medicines (pharmacy_id, lower(brand_name), lower(generic_name));
create index if not exists batches_medicine_expiry_idx
  on public.batches (medicine_id, expiry_date);
create index if not exists batches_pharmacy_idx
  on public.batches (pharmacy_id);

alter table public.medicines enable row level security;
alter table public.batches enable row level security;

drop policy if exists "Pharmacy owners manage medicines" on public.medicines;
create policy "Pharmacy owners manage medicines"
  on public.medicines for all
  using (pharmacy_id = (select auth.uid()))
  with check (pharmacy_id = (select auth.uid()));

drop policy if exists "Pharmacy owners manage batches" on public.batches;
create policy "Pharmacy owners manage batches"
  on public.batches for all
  using (pharmacy_id = (select auth.uid()))
  with check (pharmacy_id = (select auth.uid()));

