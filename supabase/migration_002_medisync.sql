-- Add one medicine and one stock batch safely. The unique batch constraint is updated.
create or replace function public.add_medicine_stock(
  p_medicine jsonb,
  p_quantity integer,
  p_batch_number text,
  p_mfg_date date,
  p_expiry_date date,
  p_purchase_price numeric,
  p_selling_price numeric,
  p_reorder_level integer
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_pharmacy_id uuid := auth.uid();
  v_medicine_id uuid;
begin
  if v_pharmacy_id is null then raise exception 'Authentication required'; end;
  if p_quantity is null or p_quantity < 0 then raise exception 'Quantity cannot be negative'; end;
  if p_expiry_date is null then raise exception 'Expiry date is required'; end;
  if p_reorder_level is null or p_reorder_level < 0 then raise exception 'Reorder level cannot be negative'; end;

  select id into v_medicine_id
  from public.medicines
  where pharmacy_id = v_pharmacy_id
    and lower(brand_name) = lower(btrim(p_medicine->>'brand_name'))
    and lower(generic_name) = lower(btrim(p_medicine->>'generic_name'))
    and lower(strength) = lower(btrim(coalesce(p_medicine->>'strength','')))
    and dosage_form = btrim(p_medicine->>'dosage_form')
    and lower(pack_size) = lower(btrim(coalesce(p_medicine->>'pack_size','')))
  limit 1;

  if v_medicine_id is null then
    insert into public.medicines (
      pharmacy_id, brand_name, generic_name, strength, dosage_form, pack_size,
      manufacturer, image_url, unit, reorder_level, selling_price
    ) values (
      v_pharmacy_id,
      btrim(p_medicine->>'brand_name'),
      btrim(p_medicine->>'generic_name'),
      coalesce(p_medicine->>'strength',''),
      btrim(p_medicine->>'dosage_form'),
      coalesce(p_medicine->>'pack_size',''),
      nullif(p_medicine->>'manufacturer',''),
      nullif(p_medicine->>'image_url',''),
      coalesce(p_medicine->>'unit','tablets'),
      p_reorder_level,
      p_selling_price
    )
    returning id into v_medicine_id;
  else
    update public.medicines
    set reorder_level = p_reorder_level,
        selling_price = p_selling_price
    where id = v_medicine_id;
  end;

  if p_quantity > 0 then
    insert into public.batches (
      medicine_id, pharmacy_id, batch_number, mfg_date, expiry_date,
      quantity, purchase_price, selling_price
    ) values (
      v_medicine_id, v_pharmacy_id, btrim(p_batch_number), p_mfg_date, p_expiry_date,
      p_quantity, p_purchase_price, p_selling_price
    )
    on conflict (medicine_id, batch_number) do update
      set quantity = public.batches.quantity + excluded.quantity,
          mfg_date = coalesce(excluded.mfg_date, public.batches.mfg_date),
          expiry_date = excluded.expiry_date,
          purchase_price = excluded.purchase_price,
          selling_price = excluded.selling_price;
  end;

  return v_medicine_id;
end;
$$;

revoke all on function public.add_medicine_stock(jsonb,integer,text,date,date,numeric,numeric,integer)
  from public, anon;
grant execute on function public.add_medicine_stock(jsonb,integer,text,date,date,numeric,numeric,integer)
  to authenticated;

-- Demo loader: only creates rows for the authenticated pharmacy.
create or replace function public.load_demo_inventory()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_pharmacy_id uuid := auth.uid();
  v_count integer := 0;
begin
  if v_pharmacy_id is null then raise exception 'Authentication required'; end;

  if exists (select 1 from public.medicines where pharmacy_id = v_pharmacy_id) then
    return 0;
  end;

  insert into public.medicines
  (pharmacy_id,brand_name,generic_name,strength,dosage_form,pack_size,manufacturer,unit,reorder_level,selling_price)
  select v_pharmacy_id,d.brand_name,d.generic_name,d.strength,d.dosage_form,d.pack_size,d.manufacturer,d.unit,d.reorder_level,d.selling_price
  from (values
    ('Paracetamol','Paracetamol','500 mg','tablet','10 tablets',null,'tablets',20,25.00),
    ('Cetirizine','Cetirizine','10 mg','tablet','10 tablets',null,'tablets',10,18.00),
    ('ORS','Oral rehydration salts','WHO formula','powder','1 sachet',null,'strips',10,20.00),
    ('Omeprazole','Omeprazole','20 mg','capsule','10 capsules',null,'strips',8,32.00),
    ('Azithromycin','Azithromycin','250 mg','tablet','6 tablets',null,'tablets',6,66.00),
    ('Vitamin D3','Cholecalciferol','60,000 IU','powder','1 sachet',null,'strips',5,22.00),
    ('Amoxicillin','Amoxicillin','500 mg','capsule','10 capsules',null,'strips',6,45.00),
    ('Calcium','Calcium','500 mg','tablet','15 tablets',null,'tablets',12,28.00),
    ('Cough Syrup','Cough expectorant','','bottle','100 ml',null,'bottles',6,75.00),
    ('Diclofenac Gel','Diclofenac','10 mg/g','cream','30 g',null,'boxes',5,95.00),
    ('Metformin','Metformin','500 mg','tablet','10 tablets',null,'tablets',15,30.00),
    ('Atorvastatin','Atorvastatin','10 mg','tablet','10 tablets',null,'tablets',8,40.00)
  ) d(brand_name,generic_name,strength,dosage_form,pack_size,manufacturer,unit,reorder_level,selling_price);

  get diagnostics v_count = row_count;

  insert into public.batches
  (medicine_id,pharmacy_id,batch_number,expiry_date,quantity,purchase_price,selling_price)
  select m.id,v_pharmacy_id,
    case m.brand_name
      when 'Paracetamol' then 'DEM-PARA-001'
      when 'Cetirizine' then 'DEM-CET-001'
      when 'ORS' then 'DEM-ORS-001'
      when 'Omeprazole' then 'DEM-OME-001'
      when 'Azithromycin' then 'DEM-AZI-001'
      when 'Vitamin D3' then 'DEM-D3-001'
      when 'Amoxicillin' then 'DEM-AMX-001'
      when 'Calcium' then 'DEM-CAL-001'
      when 'Cough Syrup' then 'DEM-CS-001'
      when 'Diclofenac Gel' then 'DEM-DIC-001'
      when 'Metformin' then 'DEM-MET-001'
      else 'DEM-ATO-001'
    end,
    case m.brand_name
      when 'Vitamin D3' then (current_date + interval '20 days')::date
      when 'Cough Syrup' then (current_date + interval '25 days')::date
      else (current_date + interval '300 days')::date
    end,
    case m.brand_name
      when 'Cetirizine' then 0
      when 'ORS' then 0
      when 'Omeprazole' then 5
      when 'Azithromycin' then 4
      when 'Vitamin D3' then 3
      when 'Amoxicillin' then 4
      else 24
    end,
    10.00,
    m.selling_price
  from public.medicines m
  where m.pharmacy_id = v_pharmacy_id;

  return v_count;
end;
$$;

